package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/build"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Generate from the same GOOS/GOARCH-selected declarations the WASM build uses.
func main() {
	root := os.Args[1]
	var out bytes.Buffer
	out.WriteString("//go:build js && wasm\n\n// Code generated by scripts/native-registry; DO NOT EDIT.\npackage main\nimport (\"reflect\";\"context\";\"github.com/Calcium-Ion/moejs\";\"github.com/Calcium-Ion/moejs/engine\")\n")
	ctx := build.Default
	ctx.GOOS = "js"
	ctx.GOARCH = "wasm"
	for _, pkg := range []struct{ name, dir string }{{"engine", "external/moejs/engine"}, {"moejs", "external/moejs"}} {
		entries, e := os.ReadDir(filepath.Join(root, pkg.dir))
		must(e)
		values := map[string]string{}
		types := map[string]string{}
		for _, entry := range entries {
			name := entry.Name()
			if entry.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
				continue
			}
			match, e := ctx.MatchFile(filepath.Join(root, pkg.dir), name)
			must(e)
			if !match {
				continue
			}
			f, e := parser.ParseFile(token.NewFileSet(), filepath.Join(root, pkg.dir, name), nil, 0)
			must(e)
			for _, decl := range f.Decls {
				switch d := decl.(type) {
				case *ast.FuncDecl:
					if d.Recv == nil && ast.IsExported(d.Name.Name) && d.Type.TypeParams == nil {
						values[d.Name.Name] = pkg.name + "." + d.Name.Name
					}
				case *ast.GenDecl:
					numericConst := false
					for _, spec := range d.Specs {
						switch s := spec.(type) {
						case *ast.TypeSpec:
							if ast.IsExported(s.Name.Name) && s.TypeParams == nil {
								types[s.Name.Name] = "reflect.TypeOf((*" + pkg.name + "." + s.Name.Name + ")(nil)).Elem()"
							}
						case *ast.ValueSpec:
							if d.Tok == token.CONST && len(s.Values) > 0 {
								numericConst = s.Type == nil
								for _, value := range s.Values {
									if lit, ok := value.(*ast.BasicLit); ok && (lit.Kind == token.STRING || lit.Kind == token.CHAR) {
										numericConst = false
									}
									if id, ok := value.(*ast.Ident); ok && (id.Name == "true" || id.Name == "false") {
										numericConst = false
									}
								}
							}
							if s.Type != nil {
								numericConst = false
							}
							for _, id := range s.Names {
								if !ast.IsExported(id.Name) {
									continue
								}
								expression := pkg.name + "." + id.Name
								if d.Tok == token.CONST && numericConst {
									expression = "float64(" + expression + ")"
								}
								values[id.Name] = expression
							}
						}
					}
				}
			}
		}
		fmt.Fprintf(&out, "func nativeRegistry_%s()map[string]any{return map[string]any{\n", pkg.name)
		names := sorted(values)
		for _, name := range names {
			fmt.Fprintf(&out, "%q:%s,\n", name, values[name])
		}
		out.WriteString("\"Background\":context.Background,\"TODO\":context.TODO,\n}}\n")
		fmt.Fprintf(&out, "func nativeRegistryTypes_%s()map[string]reflect.Type{return map[string]reflect.Type{\n", pkg.name)
		for _, name := range sorted(types) {
			fmt.Fprintf(&out, "%q:%s,\n", pkg.name+"."+name, types[name])
		}
		out.WriteString("}}\n")
	}
	source, e := format.Source(out.Bytes())
	must(e)
	must(os.WriteFile(filepath.Join(root, "bridge/native_registry.go"), source, 0644))
}
func must(err error) {
	if err != nil {
		panic(err)
	}
}
func sorted(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for key := range m {
		out = append(out, key)
	}
	sort.Strings(out)
	return out
}
